def compute_self_proxy(act_npz, conn_npz, dmn_indices, bands):
  self_proxy = {}

  for band in bands:

    act = act_npz[band]
    conn = conn_npz[band]

    dmn_act = act[dmn_indices].mean()

    dmn_block = conn[np.ix_(dmn_indices, dmn_indices)]
    dmn_con = dmn_block[np.triu_indices_from(dmn_block, k = 1)].mean()

    self_proxy[band] = {
        'dmn_act': dmn_act,
        'dmn_con': dmn_con,
    }

  return self_proxy

def compute_strat_proxy(act_npz, conn_npz, dmn_indices, cen_indices, sn_indices, bands):
  strat_proxy = {}

  for band in bands:
    act = act_npz[band]
    conn = conn_npz[band]

    cen_act = act[cen_indices].mean()

    sn_cen_block = conn[np.ix_(sn_indices, cen_indices)]
    sn_cen_con = sn_cen_block.mean()

    sn_dmn_block = conn[np.ix_(sn_indices, dmn_indices)]
    sn_dmn_con = sn_dmn_block.mean()

    strat_proxy[band] = {
        'cen_act': cen_act,
        'sn_cen_con': sn_cen_con,
        'sn_dmn_con': sn_dmn_con,
    }

  return strat_proxy

