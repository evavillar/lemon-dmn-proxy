def preprocess_sub (sub_id, drive_extracted):
  vhdr_path = glob.glob(f'{drive_extracted}/{sub_id}/**/*.vhdr', recursive = True)[0]
  raw = mne.io.read_raw_brainvision(vhdr_path, preload = True)

  raw.set_channel_types({'VEOG' : 'eog'})
  montage = mne.channels.make_standard_montage('easycap-M1')
  raw.set_montage(montage)

  raw.resample(250, npad = 'auto')
  raw.filter(l_freq = 0.5, h_freq = 100)
  raw.notch_filter(freqs = 50)

  noisy = NoisyChannels(raw, random_state = 123)
  noisy.find_all_bads()
  raw.info['bads'] = noisy.get_bads()
  raw.interpolate_bads(reset_bads = True)

  raw_ica = raw.copy()
  raw_ica.set_eeg_reference('average', projection = True)
  raw_ica.apply_proj()

  ica = mne.preprocessing.ICA(n_components = 0.99, method = 'infomax',
                              fit_params = dict(extended = True), random_state = 123)
  ica.fit(raw_ica)

  exclude_labels = ['eye blink', 'muscle artifact', 'heart beat']
  labels = label_components(raw_ica, ica, method = 'iclabel')
  ica.exclude = [l for l, (label, prob) in enumerate(zip(labels['labels'], labels['y_pred_proba']))
                 if label in exclude_labels and prob > 0.8]

  raw_clean = raw.copy()
  raw_clean.set_eeg_reference('average', projection = True)
  raw_clean.apply_proj()
  ica.apply(raw_clean)

  qc_row = {
      'subject' : sub_id,
      'n_bad_channels' : len(noisy.get_bads()),
      'n_components_total' : ica.n_components_,
      'n_excluded' : len(ica.exclude),
      'excluded_labels' : [labels['labels'][l] for l in ica.exclude],
  }
  return raw_clean, qc_row

