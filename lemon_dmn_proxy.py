def extract_ec_mark (raw_clean, ec_key = 'Stimulus/S210', gap_threshold = 10.0) :
  events, event_id = mne.events_from_annotations(raw_clean)
  ec_events = events[events[:,2] == event_id[ec_key]]
  mark_samples = ec_events[:,0]
  mark_times = mark_samples / raw_clean.info['sfreq']

  ec_start = np.concatenate([[True], np.diff(mark_times) > gap_threshold])
  ec_block_onset = mark_samples[ec_start]

  return ec_block_onset

