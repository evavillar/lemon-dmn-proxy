def band_activity(sub_id, drive_network, bands):
  epochs = mne.read_epochs(f'{drive_network}/{sub_id}_network-epo.fif', preload = True)

  results = {}
  for band_name, (lo, hi) in bands.items():
    epochs_band = epochs.copy().filter(l_freq = lo, h_freq = hi, picks = 'all')
    data = epochs_band.get_data()

    envelope = np.abs(hilbert(data, axis = -1))
    act = envelope.mean(axis = (0,2))

    results[band_name] = act

  return results

def band_connectivity(sub_id, drive_network, bands):
  epochs = mne.read_epochs(f'{drive_network}/{sub_id}_network-epo.fif', preload = True)

  results = {}
  for band_name, (lo, hi) in bands.items():
    epochs_band = epochs.copy().filter(l_freq = lo, h_freq = hi, picks = 'all')
    data = epochs_band.get_data()
    conn = envelope_correlation(data, orthogonalize = 'pairwise')
    conn_matrix = conn.get_data(output = 'dense').mean(axis = 0)[:,:,0]
    results[band_name] = conn_matrix

  return results

