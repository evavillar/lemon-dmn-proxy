def subject_source_localization (sub_id, epochs_path, fwd, labels_dmn, labels_cen, labels_sn):
  epochs = mne.read_epochs(epochs_path, preload = True)

  noise_cov = mne.compute_covariance(epochs, method = 'shrunk')
  inv = mne.minimum_norm.make_inverse_operator(
      epochs.info, fwd, noise_cov, loose = 0.2, depth = 0.8
  )

  stc_generator = mne.minimum_norm.apply_inverse_epochs(
      epochs, inv, lambda2 = 1.0/9.0, method = 'eLORETA',
      return_generator = True
  )

  labels_networks = labels_dmn + labels_cen + labels_sn
  label_names = [l.name for l in labels_networks]
  label_tcs = mne.extract_label_time_course(
      stc_generator, labels_networks, fwd['src'], mode = 'pca_flip'
  )

  info = mne.create_info(ch_names = label_names, sfreq = epochs.info['sfreq'], ch_types = 'misc')
  label_epochs = mne.EpochsArray(np.array(label_tcs), info, tmin = epochs.tmin)

  return label_epochs, label_names

